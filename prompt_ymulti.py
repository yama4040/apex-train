def build_prompt(features):
    """LLMへ送るプロンプト全文を組み立てる。"""
    missing = [k for k in FEATURE_KEYS if k not in features]
    if missing:
        raise KeyError(f"プロンプトに必要なキーがありません: {missing}")
    return SYSTEM_INSTRUCTION + build_current_status(features) + OUTPUT_FORMAT


